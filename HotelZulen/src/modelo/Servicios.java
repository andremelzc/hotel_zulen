package modelo;

/**
 *
 * @author Suyco
 */
public class Servicios {
    int id;
    String concepto;
    double costo;

    public Servicios() {
    }

    public Servicios(int id, String concepto, double costo) {
        this.id = id;
        this.concepto = concepto;
        this.costo = costo;
    }

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    public String getConcepto() {
        return concepto;
    }

    public void setConcepto(String concepto) {
        this.concepto = concepto;
    }

    public double getCosto() {
        return costo;
    }

    public void setCosto(double costo) {
        this.costo = costo;
    }
    
}
